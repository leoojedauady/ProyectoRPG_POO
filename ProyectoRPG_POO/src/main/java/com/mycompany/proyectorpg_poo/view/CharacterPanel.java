    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        try {
            Character character = controller.registerCharacter(txtName.getText(), (String) cmbType.getSelectedItem(),
                    (int) spnLevel.getValue(), txtHealth.getText());
            mainFrame.addInfo("Personaje registrado: " + character);
            clearForm();
            refreshData();
        } catch (InvalidCharacterStateException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Datos inválidos", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

