    public void refreshData() {
        int selectedRow = tblCharacters.getSelectedRow();
        Object selectedTarget = cmbTarget.getSelectedItem();

        DefaultTableModel model = (DefaultTableModel) tblCharacters.getModel();
        model.setRowCount(0);
        cmbTarget.removeAllItems();

        for (Character character : controller.getCharacters()) {
            model.addRow(new Object[]{
                character.getName(),
                character.getCharacterType(),
                character.getLevel(),
                character.getHealth() + "/" + character.getMaxHealth(),
                character.isAlive() ? "Vivo" : "Muerto"
            });
            cmbTarget.addItem(character);
        }

        if (selectedTarget != null) {
            cmbTarget.setSelectedItem(selectedTarget);
        }
        if (selectedRow != -1 && selectedRow < model.getRowCount()) {
            tblCharacters.setRowSelectionInterval(selectedRow, selectedRow);
        }
        showDetails();
    }

    private void showDetails() {
        int row = tblCharacters.getSelectedRow();
        if (row == -1) {
            txtDetails.setText("");
            return;
        }

        Character character = controller.getCharacter(row);
        txtDetails.setText("Nombre: " + character.getName()
                + "\nTipo: " + character.getCharacterType()
                + "\nNivel: " + character.getLevel()
                + "\nSalud: " + character.getHealth() + "/" + character.getMaxHealth()
                + "\nEstado: " + (character.isAlive() ? "Vivo" : "Muerto")
                + "\nFuerza: " + character.getStrength()
                + "\nDefensa: " + character.getDefense()
                + "\n" + character.getSpecificInfo());
    }

    private void clearForm() {
        txtName.setText("");
        cmbType.setSelectedIndex(0);
        spnLevel.setValue(1);
        txtHealth.setText("100");
    }

