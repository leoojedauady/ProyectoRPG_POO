    private void btnAttackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAttackActionPerformed
        int row = tblCharacters.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona en la tabla el personaje que va a atacar.");
            return;
        }

        Character attacker = controller.getCharacter(row);
        Character target = (Character) cmbTarget.getSelectedItem();
        try {
            controller.attack(attacker, target);
            mainFrame.addInfo(attacker.getName() + " atacó a " + target.getName() + ". Salud de "
                    + target.getName() + ": " + target.getHealth() + "/" + target.getMaxHealth());
        } catch (InvalidCharacterStateException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Acción inválida", JOptionPane.WARNING_MESSAGE);
        }
        refreshData();
    }//GEN-LAST:event_btnAttackActionPerformed

