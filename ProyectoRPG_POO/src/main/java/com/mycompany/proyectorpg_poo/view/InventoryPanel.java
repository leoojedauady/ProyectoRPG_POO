    public void refreshData() {
        Object selected = cmbCharacter.getSelectedItem();
        cmbCharacter.removeAllItems();
        for (Character character : controller.getCharacters()) {
            cmbCharacter.addItem(character);
        }
        if (selected != null) {
            cmbCharacter.setSelectedItem(selected);
        }
        refreshItems();
    }

    private void refreshItems() {
        DefaultTableModel model = (DefaultTableModel) tblItems.getModel();
        model.setRowCount(0);

        Character character = (Character) cmbCharacter.getSelectedItem();
        if (character == null) {
            lblSummary.setText("No hay personajes registrados.");
            return;
        }

        for (Item item : controller.getItems(character)) {
            model.addRow(new Object[]{
                item.getId(),
                item.getName(),
                item.getDescription(),
                item.getWeight(),
                item.getValue()
            });
        }
        lblSummary.setText(controller.getSummary(character));
    }

    // solo se ven los campos del tipo de objeto elegido
    private void showItemFields() {
        String type = (String) cmbItemType.getSelectedItem();
        pnlWeapon.setVisible(type.equals("Weapon"));
        pnlArmor.setVisible(type.equals("Armor"));
        pnlPotion.setVisible(type.equals("Potion"));
        pnlAccessory.setVisible(type.equals("Accessory"));
        pnlConsumable.setVisible(type.equals("Consumable"));
    }

    private double readWeight(javax.swing.JTextField field) {
        double weight = Double.parseDouble(field.getText().trim());
        if (weight <= 0) {
            throw new NumberFormatException();
        }
        return weight;
    }

