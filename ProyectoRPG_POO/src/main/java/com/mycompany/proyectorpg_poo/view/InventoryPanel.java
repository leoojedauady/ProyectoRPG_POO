    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        Character character = (Character) cmbCharacter.getSelectedItem();
        if (character == null) {
            JOptionPane.showMessageDialog(this, "Primero registra y selecciona un personaje.");
            return;
        }

        String name = txtItemName.getText().trim();
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El objeto debe tener un nombre.", "Datos inválidos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int value = (int) spnItemValue.getValue();
        String type = (String) cmbItemType.getSelectedItem();
        try {
            if (type.equals("Weapon")) {
                controller.addWeapon(character, name, readWeight(txtWeaponWeight), value,
                        (int) spnWeaponDamage.getValue(), txtWeaponType.getText());
            } else if (type.equals("Armor")) {
                controller.addArmor(character, name, readWeight(txtArmorWeight), value,
                        (int) spnArmorDefense.getValue(), txtArmorType.getText());
            } else if (type.equals("Potion")) {
                controller.addPotion(character, name, value, (String) cmbEffectType.getSelectedItem(),
                        (int) spnEffectValue.getValue());
            } else if (type.equals("Accessory")) {
                controller.addAccessory(character, name, value, (int) spnBonusHealth.getValue(),
                        (int) spnBonusMana.getValue(), (int) spnBonusStrength.getValue(), (int) spnBonusDefense.getValue());
            } else {
                controller.addConsumable(character, name, value, txtConsumableEffect.getText());
            }
            mainFrame.addInfo(name + " se agregó al inventario de " + character.getName() + ".");
            txtItemName.setText("");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El peso debe ser un número mayor a 0 (por ejemplo 2.5).", "Datos inválidos", JOptionPane.WARNING_MESSAGE);
        } catch (InventoryFullException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Inventario lleno", JOptionPane.WARNING_MESSAGE);
        }
        refreshItems();
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
        Character character = (Character) cmbCharacter.getSelectedItem();
        int row = tblItems.getSelectedRow();
        if (character == null || row == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona un objeto del inventario para eliminarlo.");
            return;
        }

        Item item = controller.getItems(character).get(row);
        try {
            controller.removeItem(character, item);
            mainFrame.addInfo(item.getName() + " se eliminó del inventario de " + character.getName() + ".");
        } catch (ItemNotFoundException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Objeto no encontrado", JOptionPane.WARNING_MESSAGE);
        }
        refreshItems();
    }//GEN-LAST:event_btnRemoveActionPerformed

