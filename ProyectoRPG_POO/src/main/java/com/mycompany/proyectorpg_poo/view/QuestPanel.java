    public void refreshData() {
        int selectedRow = tblQuests.getSelectedRow();
        Object selectedCharacter = cmbCharacter.getSelectedItem();

        DefaultTableModel model = (DefaultTableModel) tblQuests.getModel();
        model.setRowCount(0);
        for (Quest quest : controller.getQuests()) {
            model.addRow(new Object[]{
                quest.getId(),
                quest.getName(),
                quest.getDifficulty(),
                quest.getStatus(),
                quest.getParticipants().size(),
                quest.getExperienceReward(),
                quest.getGoldReward()
            });
        }

        cmbCharacter.removeAllItems();
        for (Character character : controller.getCharacters()) {
            cmbCharacter.addItem(character);
        }
        if (selectedCharacter != null) {
            cmbCharacter.setSelectedItem(selectedCharacter);
        }

        if (selectedRow != -1 && selectedRow < model.getRowCount()) {
            tblQuests.setRowSelectionInterval(selectedRow, selectedRow);
        }
        showQuestDetails();
    }

    private void showQuestDetails() {
        DefaultListModel<Character> listModel = new DefaultListModel<>();
        int row = tblQuests.getSelectedRow();
        if (row == -1) {
            txtQuestInfo.setText("");
            lstParticipants.setModel(listModel);
            return;
        }

        Quest quest = controller.getQuest(row);
        txtQuestInfo.setText("Nombre: " + quest.getName()
                + "\nDificultad: " + quest.getDifficulty()
                + "\nEstado: " + quest.getStatus()
                + "\nRecompensa: " + quest.getExperienceReward() + " XP y " + quest.getGoldReward() + " de oro"
                + "\nDescripción: " + quest.getDescription());

        for (Character character : quest.getParticipants()) {
            listModel.addElement(character);
        }
        lstParticipants.setModel(listModel);
    }

    private void clearForm() {
        txtQuestName.setText("");
        txtDescription.setText("");
        cmbDifficulty.setSelectedIndex(0);
        spnExperience.setValue(100);
        spnGold.setValue(50);
    }

    private Quest getSelectedQuest() {
        int row = tblQuests.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una misión de la tabla.");
            return null;
        }
        return controller.getQuest(row);
    }

