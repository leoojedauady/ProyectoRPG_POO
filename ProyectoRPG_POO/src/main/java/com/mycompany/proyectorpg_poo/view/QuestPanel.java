    private void btnAddParticipantActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddParticipantActionPerformed
        Quest quest = getSelectedQuest();
        if (quest == null) {
            return;
        }

        Character character = (Character) cmbCharacter.getSelectedItem();
        try {
            controller.addParticipant(quest, character);
            mainFrame.addInfo(character.getName() + " se unió a la misión " + quest.getName() + ".");
        } catch (InvalidQuestOperationException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Operación no permitida", JOptionPane.WARNING_MESSAGE);
        }
        refreshData();
    }//GEN-LAST:event_btnAddParticipantActionPerformed

    private void btnRemoveParticipantActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveParticipantActionPerformed
        Quest quest = getSelectedQuest();
        if (quest == null) {
            return;
        }

        Character character = lstParticipants.getSelectedValue();
        if (character == null) {
            JOptionPane.showMessageDialog(this, "Selecciona un participante de la lista.");
            return;
        }

        try {
            controller.removeParticipant(quest, character);
            mainFrame.addInfo(character.getName() + " salió de la misión " + quest.getName() + ".");
        } catch (InvalidQuestOperationException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Operación no permitida", JOptionPane.WARNING_MESSAGE);
        }
        refreshData();
    }//GEN-LAST:event_btnRemoveParticipantActionPerformed

    private void btnCompleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompleteActionPerformed
        Quest quest = getSelectedQuest();
        if (quest == null) {
            return;
        }

        try {
            controller.completeQuest(quest);
            mainFrame.addInfo("Misión completada: " + quest.getName() + ". Cada participante recibió "
                    + quest.getGoldReward() + " de oro.");
        } catch (InvalidQuestOperationException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Operación no permitida", JOptionPane.WARNING_MESSAGE);
        }
        refreshData();
    }//GEN-LAST:event_btnCompleteActionPerformed

    private void btnFailActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFailActionPerformed
        Quest quest = getSelectedQuest();
        if (quest == null) {
            return;
        }

        try {
            controller.failQuest(quest);
            mainFrame.addInfo("La misión " + quest.getName() + " falló.");
        } catch (InvalidQuestOperationException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Operación no permitida", JOptionPane.WARNING_MESSAGE);
        }
        refreshData();
    }//GEN-LAST:event_btnFailActionPerformed

