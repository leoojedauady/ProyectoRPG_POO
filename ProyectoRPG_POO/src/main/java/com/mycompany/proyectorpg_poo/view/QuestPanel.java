    private void btnRegisterQuestActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterQuestActionPerformed
        try {
            Difficulty difficulty = Difficulty.valueOf((String) cmbDifficulty.getSelectedItem());
            Quest quest = controller.registerQuest(txtQuestName.getText(), txtDescription.getText(), difficulty,
                    (int) spnExperience.getValue(), (int) spnGold.getValue());
            mainFrame.addInfo("Misión registrada: " + quest.getName());
            clearForm();
            refreshData();
        } catch (InvalidQuestOperationException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Datos inválidos", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnRegisterQuestActionPerformed

